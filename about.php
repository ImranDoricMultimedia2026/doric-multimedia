<script>
document.addEventListener("DOMContentLoaded", function () {

    /* ============================================
       DIRECTOR CARD 3D TILT
    ============================================ */

    const directorCards = document.querySelectorAll("[data-tilt-card]");

    directorCards.forEach(function (card) {

        const inner = card.querySelector(".director-card-inner");

        if (!inner) return;

        card.addEventListener("mousemove", function (event) {

            const rect = card.getBoundingClientRect();

            const x = event.clientX - rect.left;
            const y = event.clientY - rect.top;

            const rotateY = ((x / rect.width) - 0.5) * 10;
            const rotateX = ((y / rect.height) - 0.5) * -10;

            card.style.transform =
                "translateY(-10px) " +
                "rotateX(" + rotateX + "deg) " +
                "rotateY(" + rotateY + "deg)";

            inner.style.setProperty("--mouse-x", x + "px");
            inner.style.setProperty("--mouse-y", y + "px");

        });

        card.addEventListener("mouseleave", function () {

            card.style.transform = "translateY(0) rotateX(0deg) rotateY(0deg)";

            inner.style.setProperty("--mouse-x", "50%");
            inner.style.setProperty("--mouse-y", "50%");

        });

    });


    /* ============================================
       PREMIUM FEATURE ITEM CLICK
    ============================================ */

    const featureItems = document.querySelectorAll(".premium-feature-item");

    featureItems.forEach(function (item) {

        item.addEventListener("click", function () {

            this.style.transform = "scale(0.95)";

            setTimeout(function () {
                item.style.transform = "";
            }, 200);

        });

    });


    /* ============================================
       DEBUG
    ============================================ */

    console.log("About page JS loaded successfully.");
    console.log("Director cards:", directorCards.length);
    console.log("Feature items:", featureItems.length);

});
</script>
